"""Generating the published comparison table from the capability data.

`docs/benchmarks/protocol-support.md` is generated from `caps.FEATURES` and
`caps.Core.notes`, never written by hand. A hand-maintained table of what four
projects support drifts within a release, and a drifted capability table is worse
than none: it is the document someone checks before filing a missing-feature
report.

`bench.py --emit-support-doc` writes it; the CI job that runs on every pull
request regenerates it and fails if the file on disk differs, so a change to the
capability data cannot land without the document changing with it.
"""

from __future__ import annotations

from pathlib import Path

from . import caps

HEADER = """<!-- Generated by docs/benchmarks/harness/bench.py --emit-support-doc.
     Edit zbench/caps.py instead; CI fails when this file is out of date. -->

# Connection support across the four cores

{intro}

## Versions

{table}

{pinned_note}

## Legend

| Value | Meaning |
|---|---|
| `yes` | supported at the pinned version |
| `partial` | supported with a documented restriction |
| `deprecated` | still works; the project directs new configurations elsewhere |
| `alpha` / `prerelease` | present in an alpha or unreleased line, not in the pinned version |
| `removed` | the project reports the feature as removed |
| `no` | not supported |
| `n-a` | the concept does not exist in that project's configuration model |

A cell in the tables below is a statement about what a project can be
**configured** to do. It is not a statement about what the benchmark in
`docs/benchmarks` measures: most of this surface cannot be reached by a
single-process client on loopback, which is precisely why it is written down
here instead of being left to be discovered.

## Charts

Two views of the same data, generated alongside a benchmark run and also
standalone:

- `charts/protocol-transport-grid.png` -- one panel per core, protocol against
  transport, `1.00` where the core can be configured for that combination and
  `0.00` where it cannot. The empty cells are the gaps.
- `charts/capability-surface.png` -- every row of these tables, all four cores,
  on one scale, so a column can be read top to bottom.
"""


def _versions_table() -> str:
    lines = [
        "| Project | Version | Source | Note |",
        "|---|---|---|---|",
    ]
    for core_id in ("zray", "xray", "singbox", "xray-rust"):
        pin = caps.PINS[core_id]
        lines.append(
            f"| [{pin['project']}]({pin['repo']}) | `{pin['version']}` | "
            f"{'built from this checkout' if core_id == 'zray' else 'release asset or source tag'} | "
            f"{pin['note']} |"
        )
    return "\n".join(lines)


def _feature_table(core_ids: list[str], labels: dict[str, str]) -> str:
    lines = [
        "| Feature | " + " | ".join(labels[c] for c in core_ids) + " | Note |",
        "|---" * (len(core_ids) + 2) + "|",
    ]
    for row in caps.FEATURES:
        values = [caps.feature_value(row, c) for c in core_ids]
        note = row.note or ""
        lines.append(f"| {row.feature} | " + " | ".join(values) + f" | {note} |")
    return "\n".join(lines)


def _cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _xray_rust_section() -> str:
    from . import xrayrust_suite as X

    out = ["## What this harness covers, and what it does not", ""]
    out.append(
        "Generated from `zbench/xrayrust_suite.py`, so each row is checked against "
        "the matrix rather than re-read by hand."
    )
    out.append("")
    out.append("| Measurement | Suite | Here | Status |")
    out.append("|---|---|---|---|")
    for row in X.XRAY_RUST_SUITE:
        ours = row["ours"] if row["status"] != "covered" else "measured"
        out.append(
            f"| {_cell(row['item'])} | {row['suite']} | {_cell(ours)} | "
            f"**{row['status']}** |"
        )
    out.append("")
    out.append(
        f"{len(X.XRAY_RUST_SUITE)} areas: "
        f"{len(X.by_status('covered'))} covered, "
        f"{len(X.by_status('partial'))} partial, "
        f"{len(X.by_status('not_covered'))} not covered. "
        + (
            "Not covered: " + ", ".join(X.not_covered_items()) + ". "
            if X.not_covered_items() else ""
        )
        + "The reason in each case is in the table."
    )
    out.append("")
    out.append("### Measured here, and not by a loopback-only comparison")
    out.append("")
    out.append("| Here | A loopback-only comparison |")
    out.append("|---|---|")
    for row in X.SUPERSETS:
        out.append(f"| {_cell(row['item'])} | {_cell(row['theirs'])} |")
    out.append("")
    out.append("### What the published evidence supports")
    out.append("")
    out.append("| Claim | What we make of it |")
    out.append("|---|---|")
    for row in X.READINGS:
        out.append(f"| {_cell(row['claim'])} | {_cell(row['ours'])} |")
    out.append("")
    return "\n".join(out)


def render(core_ids: list[str] | None = None) -> str:
    core_ids = core_ids or caps.DEFAULT_CORES
    labels = {c: caps.get(c).label for c in core_ids}
    out = [
        HEADER.format(
            intro=(
                "What each of the four cores can be configured to do, at the versions "
                "below, in one place. The two questions this document exists to keep "
                "apart are *what a core supports* and *what a benchmark measured*: a "
                "core can support a connection that no loopback benchmark will ever "
                "exercise, and a benchmark can measure a connection that no user will "
                "ever configure."
            ),
            table=_versions_table(),
            pinned_note=(
                "A capability table is only true of a version. The benchmark report "
                "records the version string and the SHA-256 of every binary it "
                "actually ran; if the two disagree, the binary is the truth and this "
                "table is out of date."
            ),
        )
    ]

    for area in caps.feature_areas():
        rows = [r for r in caps.FEATURES if r.area == area]
        out.append(f"## {area}\n")
        out.append(_feature_table(core_ids, labels))
        out.append("")

    # The two directional answers, assembled from the notes rather than written
    # out longhand, so a capability change moves them too.
    out.append("## Not implemented in Zray\n")
    out.append("From `caps.ZRAY.notes`:\n")
    out.append(f"- {caps.ZRAY.notes['not_in_zray']}\n")
    out.append("## Allowed by the others and not implemented here\n")
    for core_id in core_ids:
        if core_id == "zray":
            continue
        core = caps.get(core_id)
        key = "beyond_zray" if core_id != "zray" else "not_in_zray"
        text = core.notes.get(key)
        if not text:
            continue
        out.append(f"### {core.label}\n")
        out.append(f"- {text}\n")
        out.append("Known limitations recorded for this core:\n")
        for key2, value in core.notes.items():
            if key2 == key:
                continue
            out.append(f"- **{key2}**: {value}")
        out.append("")

    out.append(_xray_rust_section())

    out.append("## Regenerating\n")
    out.append("```sh")
    out.append("cd docs/benchmarks/harness")
    out.append("python3 bench.py --emit-support-doc --check")
    out.append("```\n")
    # No generation date. A date in the file makes it unmatchable by a staleness
    # check running in a different timezone from the one that wrote it, so the
    # check fails forever for anyone not on the runner's clock -- which is every
    # contributor not on UTC. The run that measured anything records its own
    # timestamp in `manifest.json`, which is where a timestamp belongs.
    out.append(
        "_Generated by `zbench/caps.py`. The run that measured anything records "
        "its own timestamp in `manifest.json`._"
    )
    out.append("")
    return "\n".join(out)


def write(path: Path, core_ids: list[str] | None = None) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(core_ids))
    return path
